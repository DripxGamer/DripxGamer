-- Idioma ativo: o que falta num idioma cai para inglês.
-- Aceita pt-BR, pt_br, PT-BR, etc.
local function normaliseLocale(code)
    code = tostring(code or 'en'):lower():gsub('_', '-')
    return code
end

function GetLocaleTable()
    local active = Locales[normaliseLocale(Config.Locale)] or Locales.en
    local merged = {}
    for key, value in pairs(Locales.en) do merged[key] = value end
    for key, value in pairs(active) do merged[key] = value end
    return merged
end

function _U(key, ...)
    local active = Locales[normaliseLocale(Config.Locale)] or Locales.en
    local text = active[key] or Locales.en[key] or key
    if select('#', ...) > 0 then
        return string.format(text, ...)
    end
    return text
end
